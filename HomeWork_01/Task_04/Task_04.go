/*
Программа запрашивает два целых числа a и b.
Вывести все положительные числа от a (включительно) до b (включительно),
у которых в двоичной записи ровно 4 единицы (а остальные цифры — нули).
Если a > b, поменять их местами.
Пример: пользователь ввёл числа 10 и 30.
Вывод программы: 15 23 27 29 30
*/

package main

import "fmt"

func main() {

	var a, b int

	fmt.Print("Введите два целых числа a и b: ")
	fmt.Scan(&a, &b)

	// Если a > b, меняем их местами
	if a > b {
		temp := a
		a = b
		b = temp
	}

	// Перебираем все числа от a до b
	for num := a; num <= b; num++ {

		if num <= 0 {
			continue // Пропускаем неположительные числа
		}

		// Подсчитываем количество единиц в двоичной записи
		onesCount := 0
		temp := num

		for temp > 0 {
			if temp%2 == 1 {
				onesCount++
			}
			temp /= 2
		}

		// Если ровно 4 единицы, выводим число
		if onesCount == 4 {
			fmt.Print(num, " ")
		}
	}

}
